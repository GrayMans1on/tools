import assert from 'node:assert/strict';
import {textStats, splitText, replaceText, checkText, fixText} from '../tools/text-core.js';
import {fftPower} from '../tools/spectrum-core.js';
import {newBoard, validateBoard, bounds, moveObject, scaleObject} from '../tools/board-core.js';
import {tools} from '../catalog.js';
import {cardIllustration} from '../illustrations.js';
const stats = textStats('Привет мир!\n\nПривет, Влад. 123', 'Привет');
assert.equal(stats.words, 5); assert.equal(stats.paragraphs, 2); assert.equal(stats.letters, 19); assert.equal(stats.occurrences, 2);
assert.equal(textStats('👨‍👩‍👧‍👦').graphemes, 1);
assert.deepEqual(splitText('a\nb\nc\n', 'lines', 2), ['a\nb\n', 'c\n']);
assert.deepEqual(splitText('a😀b', 'characters', 2), ['a😀', 'b']);
assert.deepEqual(splitText('абв', 'bytes', 4), ['аб','в']);
assert.throws(() => splitText('😀', 'bytes', 3));
assert.deepEqual(splitText('# Первая\nТекст\n# Вторая\nЕщё', 'chapters', 1), ['# Первая\nТекст\n','# Вторая\nЕщё']);
assert.deepEqual(splitText('a---b', 'delimiter', 1, '---'), ['a','b']);
assert.equal(replaceText('cat catapult кот котик', [['cat','dog'], ['кот','пёс']], false, false, true).text, 'dog catapult пёс котик');
assert.equal(replaceText('12:34', [['(\\d+):(\\d+)','$2/$1']], true, false, false).text, '34/12');
assert.equal(replaceText('$&', [['$&','$1']], false, false, false).text, '$1');
assert.equal(replaceText('abc', [['a','b'],['b','c']], false, false, false).text, 'ccc');
assert.equal(checkText('слoво').some(item => item.rule === 'mixed'), true);
assert.equal(checkText('запрос рос').some(item => item.rule === 'repeat'), false);
assert.equal(fixText('слово слово  "да" - нет', ['repeat','spaces','quotes','dash']), 'слово «да» — нет');
const samples = Float32Array.from({length: 4096}, (_, i) => Math.sin(2 * Math.PI * 1000 * i / 48000));
const power = fftPower(samples, 0, 4096); const peak = power.indexOf(Math.max(...power));
assert.ok(Math.abs(peak * 48000 / 4096 - 1000) < 12); assert.ok(power[peak] > -2);
const board = newBoard(); assert.equal(validateBoard(structuredClone(board)).version, 1);
const object = {id:'test',type:'rect',x:10,y:20,w:100,h:50,width:3,size:24,color:'#606a86',fill:'none',text:''};
board.objects.push(object); assert.equal(validateBoard(structuredClone(board)).objects.length, 1);
moveObject(object, 5, -5); assert.deepEqual(bounds(object), {x:15,y:15,w:100,h:50});
scaleObject(object, bounds(object), 2, 2); assert.equal(bounds(object).w, 200);
assert.throws(() => validateBoard({...board, assets: {bad:'https://example.com/private.png'}}));
assert.throws(() => validateBoard({...board, objects:[{...object, color:'url(https://example.com)'}]}));
assert.equal(new Set(tools.map(tool => tool.id)).size, 48);
for (const tool of tools.filter(item => item.id !== 'pixel-nearest')) { assert.ok(cardIllustration(tool.id).includes('<svg'), tool.id); }
console.log('PASS: text statistics, Unicode graphemes, splitting, safe replacements, checks, FFT peak, board validation/transforms, catalog illustrations.');
